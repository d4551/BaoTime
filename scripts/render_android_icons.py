#!/usr/bin/env python3
"""Export static Android projections from source-bound native Icon Composer pixels.

Retains native foreground material inside canonical alpha; outside shadows and
dynamic Apple lighting are not reproduced. Writes canonical backgrounds and mipmaps,
and the shared monochrome silhouette. Adaptive alpha pixels fit the66dp-diameter
safe circle on the108dp canvas. Requires local ImageMagick7.
"""
import hashlib
import json
import math
import subprocess
import tempfile
from pathlib import Path
from render_icon_previews import CANVAS_SIZE, ICON_DIR, ROOT, apply_mask, fill_for, legacy_mask, parse_srgb, render_composition, run

DENSITIES = {"mdpi": (48, 108), "hdpi": (72, 162), "xhdpi": (96, 216),
             "xxhdpi": (144, 324), "xxxhdpi": (192, 432)}
ADAPTIVE_CANVAS_DP = 108
SAFE_DIAMETER_DP = 66
ART_DIAMETER_DP = 63


def alpha_radius(path: Path, size: int) -> float:
    pixels = subprocess.run(["magick", str(path), "-depth", "8", "rgba:-"],
                            check=True, stdout=subprocess.PIPE).stdout
    center = size / 2
    radius = max((math.hypot(index % size + 0.5 - center, index // size + 0.5 - center)
                  for index, alpha in enumerate(pixels[3::4]) if alpha), default=0)
    if radius == 0:
        raise ValueError(f"Foreground is empty: {path}")
    return radius


def verify_safe_zone(path: Path, size: int) -> None:
    radius = alpha_radius(path, size)
    allowed = size * SAFE_DIAMETER_DP / ADAPTIVE_CANVAS_DP / 2
    if radius > allowed:
        raise ValueError(f"Adaptive art crosses safe circle: {path}: {radius:.3f}px > {allowed:.3f}px")


def write_background(document: dict, appearance: str) -> None:
    fill = fill_for(document["fill-specializations"], appearance)
    stops = [parse_srgb(stop) for stop in fill["linear-gradient"]]
    if len(stops) != 2:
        raise ValueError("The authored launcher background must have two gradient stops")
    directory = ROOT / "app/src/main/res" / ("drawable" if appearance == "light" else "drawable-night")
    directory.mkdir(parents=True, exist_ok=True)
    (directory / "ic_launcher_background.xml").write_text(f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/render_android_icons.py from assets/BaoTime.icon/icon.json. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
    <path android:pathData="M0,0h108v108h-108z">
        <aapt:attr name="android:fillColor">
            <gradient android:startX="54" android:startY="0" android:endX="54" android:endY="108" android:type="linear">
                <item android:offset="0.0" android:color="{stops[0]}" />
                <item android:offset="1.0" android:color="{stops[1]}" />
            </gradient>
        </aapt:attr>
    </path>
</vector>
''')


def render_appearance(document: dict, appearance: str, work: Path) -> None:
    composition = work / f"{appearance}-composition.png"
    foreground = work / f"{appearance}-foreground.png"
    native_name = "Default" if appearance == "light" else "Dark"
    native = ROOT / f"assets/BaoTime Exports/BaoTime-iOS-{native_name}-1024@2x.png"
    run(["magick", str(native), "-resize", f"{CANVAS_SIZE}x{CANVAS_SIZE}", str(composition)])
    geometry = work / f"{appearance}-geometry.png"
    render_composition(document, appearance, geometry, work, foreground=True)
    mask = work / f"{appearance}-geometry-alpha.png"
    run(["magick", str(geometry), "-alpha", "extract", str(mask)])
    apply_mask(composition, mask, foreground)
    target_radius = CANVAS_SIZE * ART_DIAMETER_DP / ADAPTIVE_CANVAS_DP / 2
    scale = target_radius / alpha_radius(foreground, CANVAS_SIZE)
    safe_foreground = work / f"{appearance}-foreground-safe.png"
    run(["magick", str(foreground), "-resize", f"{scale * 100}%", "-gravity", "center", "-background", "none",
         "-extent", f"{CANVAS_SIZE}x{CANVAS_SIZE}", "-strip", "-depth", "8", str(safe_foreground)])
    rounded = work / f"{appearance}-rounded.png"
    circular = work / f"{appearance}-circular.png"
    run(["magick", str(composition), "-strip", "-depth", "8", str(rounded)])
    apply_mask(composition, work / "circular-mask.png", circular)
    export_densities(appearance, rounded, circular, safe_foreground, work)
    if appearance == "light":
        run(["magick", str(rounded), "-resize", "512x512", "-strip", "-depth", "8",
             str(ROOT / "assets/baotime_icon_512.png")])


def export_densities(appearance: str, rounded: Path, circular: Path, foreground: Path, work: Path) -> None:
    monochrome = work / "monochrome.png"
    if appearance == "light":
        run(["magick", str(foreground), "-fill", "white", "-colorize", "100", "-strip", "-depth", "8", str(monochrome)])
    for density, (legacy, adaptive) in DENSITIES.items():
        qualifier = density if appearance == "light" else f"night-{density}"
        output = ROOT / f"app/src/main/res/mipmap-{qualifier}"
        output.mkdir(parents=True, exist_ok=True)
        projections = [("ic_launcher.png", rounded, legacy), ("ic_launcher_round.png", circular, legacy),
                       ("ic_launcher_foreground.png", foreground, adaptive)]
        if appearance == "light":
            projections.append(("ic_launcher_monochrome.png", monochrome, adaptive))
        for name, source, size in projections:
            destination = output / name
            run(["magick", str(source), "-resize", f"{size}x{size}", "-strip", "-depth", "8", str(destination)])
            if source in (foreground, monochrome):
                verify_safe_zone(destination, size)


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def verified_inputs() -> list:
    receipt_path = ROOT / "assets/native-export-receipt.json"
    receipt = json.loads(receipt_path.read_text())
    inputs = receipt["inputs"] + receipt["exports"]
    for entry in inputs:
        if digest(ROOT / entry["path"]) != entry["sha256"]:
            raise ValueError(f"Native export is stale: {entry['path']}; re-export in Icon Composer")
    return inputs + [{"path": str(receipt_path.relative_to(ROOT)), "sha256": digest(receipt_path)}]


def write_receipt(inputs: list) -> None:
    outputs = []
    for path in sorted((ROOT / "app/src/main/res").glob("mipmap-*/*.png")):
        if not path.name.startswith("ic_launcher"):
            continue
        width, height = map(int, subprocess.run(["magick", "identify", "-format", "%w %h", str(path)],
                                check=True, stdout=subprocess.PIPE, text=True).stdout.split())
        item = {"path": str(path.relative_to(ROOT)), "sha256": digest(path),
                "appearance": "dark" if "night" in path.parent.name else "light",
                "kind": path.stem, "width": width, "height": height}
        if "foreground" in path.name or "monochrome" in path.name:
            item.update(alphaRadius=alpha_radius(path, width), safeRadius=width * SAFE_DIAMETER_DP / ADAPTIVE_CANVAS_DP / 2)
        outputs.append(item)
    for path in sorted((ROOT / "app/src/main/res").glob("drawable*/ic_launcher_background.xml")):
        outputs.append({"path": str(path.relative_to(ROOT)), "sha256": digest(path),
                        "appearance": "dark" if "night" in path.parent.name else "light",
                        "kind": "background", "width": 108, "height": 108})
    image = ROOT / "assets/baotime_icon_512.png"
    outputs.append({"path": str(image.relative_to(ROOT)), "sha256": digest(image),
                    "appearance": "light", "kind": "review", "width": 512, "height": 512})
    generator = Path(__file__).resolve()
    version = subprocess.run(["magick", "-version"], check=True, stdout=subprocess.PIPE, text=True).stdout.splitlines()[0]
    metadata = {"inputs": inputs + [{"path": "scripts/render_icon_previews.py", "sha256": digest(ROOT / "scripts/render_icon_previews.py")}],
                "generator": {"path": str(generator.relative_to(ROOT)), "sha256": digest(generator)},
                "imageMagick": version, "outputs": outputs,
                "limitations": "Static native material pixels within exact source alpha. Outside shadows and dynamic Apple refraction are not reproduced."}
    (ROOT / "assets/android-icon-export.json").write_text(json.dumps(metadata, indent=2) + "\n")


def main() -> None:
    inputs = verified_inputs()
    document = json.loads((ICON_DIR / "icon.json").read_text())
    with tempfile.TemporaryDirectory() as directory:
        work = Path(directory)
        legacy_mask(work / "rounded-mask.png", False)
        legacy_mask(work / "circular-mask.png", True)
        for appearance in ("light", "dark"):
            write_background(document, appearance)
            render_appearance(document, appearance, work)
    write_receipt(inputs)
    print("Exported canonical day/night backgrounds, distinct legacy masks and safe adaptive/monochrome art.")


if __name__ == "__main__":
    main()
